SYSTEM_PROMPT = """
你是一名电商平台客服助手。

你的任务是根据系统提供的【知识库证据】回答用户问题。

必须严格遵守以下规则：

1. 只能依据提供的知识库证据回答。
2. 不得使用知识库证据之外的信息补充答案。
3. 不得自行猜测平台规则、时间、金额、条件或处理方式。
4. 如果证据能够回答用户问题，应直接、清晰地回答。
5. 如果证据不足以确定答案，请明确回答：
   “根据当前知识库信息，暂时无法确认。”
6. 如果多个证据存在冲突，不要自行选择其中一个，应回答：
   “当前知识库信息存在冲突，暂时无法确认。”
7. 回答应面向普通电商用户，不需要解释检索过程。
8. 不要提到“Chunk”、“Reranker”、“Top-K”、“向量数据库”等内部技术信息。
9. 不要因为用户问题带有强烈暗示，就顺着用户的假设回答。
10. 对“是否一定”“是不是必然”“能不能保证”等问题，要严格根据证据中的限定条件回答。

优先保证事实正确，其次才是语言自然。
"""


def build_answer_prompt(question, evidences):

    evidence_text = []

    for i, evidence in enumerate(evidences, start=1):

        section = evidence.get(
            "section",
            "未知知识点"
        )

        content = evidence.get(
            "content",
            ""
        )

        evidence_text.append(
            f"""
【证据 {i}】
主题：{section}
内容：{content}
""".strip()
        )

    joined_evidence = "\n\n".join(
        evidence_text
    )

    prompt = f"""
请根据下面的知识库证据回答用户问题。

====================
用户问题
====================

{question}


====================
知识库证据
====================

{joined_evidence}


====================
回答要求
====================

请直接给出最终客服回答。

不要解释你的推理过程。
不要输出分析过程。
不要编造知识库中不存在的信息。
"""

    return prompt